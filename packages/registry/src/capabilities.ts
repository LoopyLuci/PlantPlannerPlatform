import type { CapabilityDef, FieldSpec, Shape } from './types';

type Extra = Omit<FieldSpec, 'type' | 'description'>;

const field = {
  str: (description: string, extra: Extra = {}): FieldSpec => ({ type: 'string', description, ...extra }),
  num: (description: string, extra: Extra = {}): FieldSpec => ({ type: 'number', description, ...extra }),
  int: (description: string, extra: Extra = {}): FieldSpec => ({ type: 'integer', description, ...extra }),
  bool: (description: string, extra: Extra = {}): FieldSpec => ({ type: 'boolean', description, ...extra }),
};

const DESIGN_ID = field.str('Design identifier, e.g. d_0123456789abcdef', { required: true, minLength: 3, maxLength: 64 });
