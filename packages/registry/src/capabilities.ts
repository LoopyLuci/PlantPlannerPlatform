export const CAPABILITY_IDS: readonly string[] = CAPABILITIES.map((c) => c.id);

export function getCapability(id: string): CapabilityDef | undefined {
  return CAPABILITIES.find((c) => c.id === id);
}

export function inputShape(id: string): Shape {
  return getCapability(id)?.input ?? {};
}
